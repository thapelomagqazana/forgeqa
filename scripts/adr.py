#!/usr/bin/env python3
"""
ADR Management Script for ForgeQA.

Usage:
    python scripts/adr.py new "Title of the Decision"
    python scripts/adr.py index
    python scripts/adr.py validate

This script automates the creation, indexing, and validation of
Architecture Decision Records (ADRs) in docs/adr/.
"""

from __future__ import annotations

import re
import sys
from datetime import date
from pathlib import Path

ADR_DIR = Path(__file__).parent.parent / "docs" / "adr"
TEMPLATE_FILE = ADR_DIR / "template.md"
INDEX_FILE = ADR_DIR / "README.md"

REQUIRED_SECTIONS = [
    "## Context",
    "## Decision",
    "## Alternatives Considered",
    "## Consequences",
    "## Reconsideration Trigger",
]


def get_existing_adrs() -> list[tuple[int, Path]]:
    """Return a sorted list of (number, path) for existing ADRs."""
    adrs: list[tuple[int, Path]] = []
    for file in ADR_DIR.glob("ADR-*.md"):
        match = re.match(r"ADR-(\d+)", file.name)
        if match:
            adrs.append((int(match.group(1)), file))
    return sorted(adrs)


def next_adr_number() -> int:
    """Return the next available ADR number."""
    adrs = get_existing_adrs()
    return adrs[-1][0] + 1 if adrs else 1


def slugify(title: str) -> str:
    """Convert a title to a kebab-case slug."""
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", title.lower()).strip("-")
    return slug


def new_adr(title: str) -> None:
    """Generate a new ADR from the template."""
    if not TEMPLATE_FILE.exists():
        print(f"Error: Template not found at {TEMPLATE_FILE}", file=sys.stderr)
        sys.exit(1)

    number = next_adr_number()
    padded = f"{number:03d}"
    filename = f"ADR-{padded}-{slugify(title)}.md"
    filepath = ADR_DIR / filename

    if filepath.exists():
        print(f"Error: {filepath} already exists.", file=sys.stderr)
        sys.exit(1)

    template = TEMPLATE_FILE.read_text()
    content = (
        template.replace("{number}", padded)
        .replace("{title}", title)
        .replace("{status}", "Proposed")
        .replace("{date}", date.today().isoformat())
        .replace("{deciders}", "Solo Developer")
        .replace("{consulted}", "None")
        .replace("{informed}", "None")
    )

    filepath.write_text(content)
    print(f"Created {filepath}")
    print("Next steps: edit the file, then run 'python scripts/adr.py index'")


def generate_index() -> None:
    """Regenerate the ADR index (docs/adr/README.md)."""
    adrs = get_existing_adrs()
    if not adrs:
        print("No ADRs found.")
        return

    lines = [
        "# Architecture Decision Records",
        "",
        "> This index is auto-generated by `python scripts/adr.py index`.",
        "> Do not edit manually.",
        "",
        "| ADR | Title | Status | Date |",
        "| :--- | :--- | :--- | :--- |",
    ]

    for number, path in adrs:
        content = path.read_text()
        title_match = re.search(r"^# ADR-\d+:\s*(.+)$", content, re.MULTILINE)
        status_match = re.search(r"> \*\*Status\*\*:\s*(.+)$", content, re.MULTILINE)
        date_match = re.search(r"> \*\*Date\*\*:\s*(.+)$", content, re.MULTILINE)

        title = title_match.group(1).strip() if title_match else "Untitled"
        status = status_match.group(1).strip() if status_match else "Unknown"
        adr_date = date_match.group(1).strip() if date_match else "Unknown"

        lines.append(f"| [{number:03d}]({path.name}) | {title} | {status} | {adr_date} |")

    INDEX_FILE.write_text("\n".join(lines) + "\n")
    print(f"Updated {INDEX_FILE} ({len(adrs)} ADRs indexed)")


def validate_adrs() -> int:
    """Validate that all ADRs contain the required sections. Returns exit code."""
    adrs = get_existing_adrs()
    if not adrs:
        print("No ADRs to validate.")
        return 0

    errors: list[str] = []
    for _, path in adrs:
        content = path.read_text()
        for section in REQUIRED_SECTIONS:
            if section not in content:
                errors.append(f"{path.name}: missing section '{section}'")

        # Check for unreplaced template placeholders
        for placeholder in ["{number}", "{title}", "{status}", "{date}"]:
            if placeholder in content:
                errors.append(f"{path.name}: unreplaced placeholder '{placeholder}'")

    if errors:
        print(f"Validation failed with {len(errors)} error(s):", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        return 1

    print(f"All {len(adrs)} ADRs are valid.")
    return 0


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)

    command = sys.argv[1]

    if command == "new":
        if len(sys.argv) < 3:
            print("Error: 'new' requires a title.", file=sys.stderr)
            print('Usage: python scripts/adr.py new "Title"', file=sys.stderr)
            sys.exit(1)
        new_adr(" ".join(sys.argv[2:]))
    elif command == "index":
        generate_index()
    elif command == "validate":
        sys.exit(validate_adrs())
    else:
        print(f"Unknown command: {command}", file=sys.stderr)
        print(__doc__)
        sys.exit(1)


if __name__ == "__main__":
    main()
